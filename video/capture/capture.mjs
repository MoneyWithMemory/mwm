// ── 3 · Approve and settle ───────────────────────────────────────────────────────────
/** Scrolls a pane to its Approve button (above the floating "Ask your AI") and clicks it. */
async function approve(scope) {
  const button = scope.getByRole('button', { name: 'Approve & Sign' })
  await ptr.glide((await scope.boundingBox()).x + 200, 520, 600)
  await page.mouse.wheel(0, 2400)
  await sleep(700)
  await ptr.click(button)
}

await scene('03-settle', async (rec) => {
  const A = paneA()
  await sleep(300)
  await approve(A)
  rec.mark('approveA')
  await sleep(700)
  if (desktop) {
    await approve(paneB())
  } else {
    // One phone, both wallets: Wallet B signs from the same screen.
    await ptr.click(A.getByRole('button', { name: 'Sign as Wallet B' }))
    await ptr.click(dialog().getByRole('button', { name: /Approve|Sign/ }).last())
  }
  rec.mark('approveB')
  await A.getByText('Swapping on Bitcoin').first().waitFor({ timeout: 10000 })
  // The seven rgb-lib calls, listed under Wallet A's detailed view.
  await ptr.glide((await A.boundingBox()).x + 200, 520, 500)
  await page.mouse.wheel(0, 2400)
  rec.mark('steps')
  await sleep(300)
  await rec.box('steps', A.getByText('Seller publishes the swap offer').first(), A.getByText('Both wallets accept the transfers').first())
  await A.getByText('Trade complete').first().waitFor({ timeout: 30000 })
  rec.mark('settled')
  await sleep(500)
  // Back up a little: "Trade complete" above the transaction id.
  await page.mouse.wheel(0, -230)
  await sleep(300)
  await rec.box('done', A.getByText('Trade complete').first(), A.getByRole('button', { name: /Back to Wallet/ }).first())
  await ptr.hover(A.getByText('Transaction ID').first(), 700)
  rec.mark('txid')
  await sleep(2200)
})

