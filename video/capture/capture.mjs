// Records the demo scenes from the frontend's built-in mock (no backend, no AI model, no Vault
// service). Start the app first: `cd frontend && npm run dev`, then `npm run capture -- desktop`
// or `npm run capture -- mobile` from video/. Clips land in public/captures/<layout>/ with a
// clips.json of their durations and named moments, which the composition reads.
//
// The mock keeps its state in the tab, so every scene runs in one page, in demo order. Setup steps
// (naming Sybil's contact, creating the Vault) happen while nothing records.
import { mkdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { chromium } from 'playwright'
import { POINTER_SCRIPT, pointer, sleep } from './pointer.mjs'
import { record } from './recorder.mjs'

const APP_URL = process.env.APP_URL ?? 'http://localhost:5173/'
const LAYOUTS = {
  desktop: { width: 1440, height: 900, dpr: 1.5 }, // 2x drops the screencast to ~20 fps on 4 cores
  mobile: { width: 390, height: 844, dpr: 2 },
}
const layoutName = process.argv[2] ?? 'desktop'
const layout = LAYOUTS[layoutName] && { ...LAYOUTS[layoutName], ...(process.env.DPR && { dpr: Number(process.env.DPR) }) }
if (!layout) throw new Error(`Unknown layout "${layoutName}": use desktop or mobile`)
const only = process.argv[3] // optional: record up to and including this scene, for quick checks

const outDir = path.resolve(import.meta.dirname, '..', 'public', 'captures', layoutName)
mkdirSync(outDir, { recursive: true })

// A throwaway password for the in-browser mock Vault. The recovery phrase is generated by Tether
// WDK at run time, read back only to pass the confirm step, and never recorded or stored.
const VAULT_PASSWORD = 'regtest-demo-only'

// The screencast ignores an emulated device scale factor: the window itself renders at 2x/3x.
const browser = await chromium.launch({
  args: [`--force-device-scale-factor=${layout.dpr}`, `--window-size=${layout.width},${layout.height}`],
})
const context = await browser.newContext({ viewport: null, colorScheme: 'dark', reducedMotion: 'no-preference' })
await context.addInitScript(POINTER_SCRIPT)
const page = await context.newPage()
const ptr = pointer(page)
const clips = {}

const dialog = () => page.locator('[role=dialog]').last()
const desktop = layoutName === 'desktop'
const paneA = () => (desktop && splitOn ? page.locator('section[aria-label="Wallet A"]') : page.locator('body'))
const paneB = () => page.locator('section[aria-label="Wallet B"]')
let splitOn = false

/**
 * Records one scene: `body` drives the page, `rec.mark(name)` names moments for captions and
 * `rec.box(name, locator)` keeps where things are for the camera.
 */
async function scene(name, body) {
  console.log(`scene ${name}`)
  await ptr.show(true)
  const rec = await record(page, path.join(outDir, `${name}.mp4`), { width: layout.width * layout.dpr, height: layout.height * layout.dpr })
  await sleep(400)
  await body(rec)
  const { seconds, marks, boxes } = await rec.stop()
  clips[name] = { file: `captures/${layoutName}/${name}.mp4`, seconds: Math.round(seconds * 1000) / 1000, marks, boxes }
  writeFileSync(path.join(outDir, 'clips.json'), JSON.stringify({ layout: layoutName, ...layout, clips }, null, 2) + '\n')
  if (only === name) {
    await browser.close()
    process.exit(0)
  }
}

